"""Write include/golf_levels.h from golf/level*.txt (see golf/README.md)."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPS = ROOT / "golf"
OUT = ROOT / "include" / "golf_levels.h"
ROWS = 15
MIN_COLUMNS = 20  # one screen
COUNT = 3


def read(path: Path):
    lines = [line.rstrip() for line in path.read_text("utf-8").splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    head = lines[0].split() if lines else []
    if len(head) != 3 or head[0] != "par":
        raise ValueError("the first line must be: par GOLD SILVER")
    gold, silver = int(head[1]), int(head[2])
    if not 0 < gold <= silver < 1000:
        raise ValueError("gold par must be above 0 and no more than silver")
    rows = lines[1:]
    if len(rows) != ROWS:
        raise ValueError(f"needs {ROWS} rows, has {len(rows)}")
    width = max(len(row) for row in rows)
    if not MIN_COLUMNS <= width <= 400:
        raise ValueError(f"must be {MIN_COLUMNS} to 400 tiles wide")
    rows = [row.replace(" ", ".").ljust(width, ".") for row in rows]
    for number, row in enumerate(rows, 2):
        for column, symbol in enumerate(row, 1):
            if symbol not in ".XHBCSF":
                raise ValueError(f"unknown symbol '{symbol}' at line "
                                 f"{number}, column {column}")
    if sum(row.count("S") for row in rows) != 1:
        raise ValueError("needs exactly one S")
    if sum(row.count("F") for row in rows) != 2 or not any(
            "FF" in row for row in rows):
        raise ValueError("needs exactly one hole, written FF")
    return gold, silver, width, rows


def main(argv=None) -> int:
    quiet = "--quiet" in (sys.argv[1:] if argv is None else argv)
    lines = ["#pragma once", "", "#include <stdint.h>", "",
             "// Generated by tools/build_golf.py from golf/ - do not edit.",
             "constexpr uint8_t GOLF_ROWS = 15;",
             f"constexpr uint8_t GOLF_COUNT = {COUNT};", ""]
    levels = []
    for number in range(1, COUNT + 1):
        path = MAPS / f"level{number}.txt"
        try:
            gold, silver, width, rows = read(path)
        except (OSError, ValueError) as error:
            print(f"golf/{path.name}: {error}", file=sys.stderr)
            return 1
        lines.append(f"constexpr const char* GOLF_MAP{number}[GOLF_ROWS] = {{")
        lines += [f'    "{row}",' for row in rows]
        lines += ["};", ""]
        levels.append(f"    {{GOLF_MAP{number}, {width}, {gold}, {silver}}},")
    lines += ["struct GolfLevel {", "  const char* const* rows;",
              "  uint16_t columns;", "  uint16_t gold;", "  uint16_t silver;",
              "};", "",
              "constexpr GolfLevel GOLF_LEVELS[GOLF_COUNT] = {"]
    lines += levels + ["};", ""]
    text = "\n".join(lines)
    if not OUT.exists() or OUT.read_text("utf-8") != text:
        OUT.write_text(text, encoding="utf-8")
        if not quiet:
            print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
