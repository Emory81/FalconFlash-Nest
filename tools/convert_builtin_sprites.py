"""Write include/games/builtin_sprites.h: the small Flashy Birds and Flashy
Golf pictures that are built into the firmware instead of being downloaded.

They work before the art reaches the branch that devices download from. Run
this after changing any of the pictures listed
below.
"""

from generate_game_assets import ROOT, SUPER_ART, convert_rgb565

OUT = ROOT / "include" / "games" / "builtin_sprites.h"
SPRITES = [("sfbCloud", "CloudTile.png"), ("sfbCoin", "Coin.png"),
           ("sfbYellowGrass", "YellowGrassTile.png"),
           ("sfbCloudBackground", "CloudBackgroundTile.png"),
           ("sfbCardboardBox", "CardboardBox.png"),
           ("sfbTennisBall", "TennisBall.png")]
# Direction blocks for sublevels: one drawing (pointing right), turned
# counterclockwise a quarter at a time.
# The Flashy Golf ball: 20 x 16, wings raised and wings down. The egg itself is
# the middle 14 pixels; the game's collision ignores the wings beside it.
GOLF_ART = ROOT / "include" / "art" / "Flashy Golf"
GOLF = [("golfEggUp", "GolfEggUp.png"), ("golfEggDown", "GolfEggDown.png")]
ARROW = "WhiteDirectionalBlock.png"
TURNS = [("sfbWhiteArrowRight", 0), ("sfbWhiteArrowUp", 1),
         ("sfbWhiteArrowLeft", 2), ("sfbWhiteArrowDown", 3)]


def add(lines, name, pixels) -> None:
    lines += ["", f"constexpr uint16_t {name}[] PROGMEM = {{"]
    for start in range(0, len(pixels), 8):
        lines.append("    " + ", ".join(
            f"0x{v:04X}" for v in pixels[start:start + 8]) + ",")
    lines.append("};")


def main() -> None:
    lines = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "// Generated by tools/convert_builtin_sprites.py.",
        "// 16 x 16 RGB565; 0xF81F is transparent.",
    ]
    for name, source in SPRITES:
        width, height, data = convert_rgb565(SUPER_ART / source)
        if width > 16 or height > 16:
            raise ValueError(f"{source} must be 16x16 or smaller")
        small = [data[i] | data[i + 1] << 8 for i in range(0, len(data), 2)]
        # Smaller art is centered in a transparent 16 x 16.
        pixels = [0xF81F] * 256
        left, top = (16 - width) // 2, (16 - height) // 2
        for y in range(height):
            start = (top + y) * 16 + left
            pixels[start:start + width] = small[y * width:(y + 1) * width]
        add(lines, name, pixels)
    width, height, data = convert_rgb565(SUPER_ART / ARROW)
    if (width, height) != (16, 16):
        raise ValueError(f"{ARROW} must be 16x16")
    pixels = [data[i] | data[i + 1] << 8 for i in range(0, len(data), 2)]
    for name, turns in TURNS:
        turned = pixels
        for _ in range(turns):
            turned = [turned[x * 16 + 15 - y]
                      for y in range(16) for x in range(16)]
        add(lines, name, turned)
    lines += ["", "// 20 x 16."]
    for name, source in GOLF:
        width, height, data = convert_rgb565(GOLF_ART / source)
        if (width, height) != (20, 16):
            raise ValueError(f"{source} must be 20x16")
        add(lines, name,
            [data[i] | data[i + 1] << 8 for i in range(0, len(data), 2)])
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
